  const structured=/^([\d:/.]+\s*[·　]?\s*)(.+)$/;
  const controls=/^(🎧 |▶ |📒 |← |✓ |📄 )(.+)$/u;
  const fragments=/^(.*?)\s*([·→：])\s*(.*?)$/;
  function translation(value){
    if(!exact.test(value))return value;
    if(words.has(value))return words.get(value);
    const icon=value.match(controls), prefix=value.match(structured), parts=value.match(fragments);
    if(icon)return icon[1]+translation(icon[2]);
    if(prefix&&prefix[2]!==value&&words.has(prefix[2]))return prefix[1]+words.get(prefix[2]);
    if(parts){const left=translation(parts[1]),right=translation(parts[3]);if(left!==parts[1]||right!==parts[3])return [left,parts[2],right].join(' ');}
    return value;
  }
